// Fabric glossary — educational reference for customers browsing the catalogue.
// Each entry describes a distinct fabric / material we manufacture with, the
// industry-standard specs, and the kinds of products it shows up in.
//
// Surfaced on /fabric-glossary and via the Fabric Glossary dropdown in the
// top navigation.

export interface FabricCare {
  label: string
}

export type FabricGroup =
  | 'Workwear & PPE'
  | 'Corporate Apparel'
  | 'Promotional & Gifts'
  | 'Event & Signage'
  | 'Sports'
  | 'Schoolwear'

export interface FabricEntry {
  /** URL slug — used as anchor (`/fabric-glossary#<slug>`) and dropdown key. */
  slug: string
  name: string
  group: FabricGroup
  weight: string         // '—' when not applicable (non-textile)
  composition: string
  weave: string          // 'N/A' for non-textile
  finish: string
  care: FabricCare[]
  /** Customer-facing positioning — what kind of work / environments it fits. */
  suitedFor: string
  /** Concrete examples of products woven from this fabric. */
  usedIn: string[]
  /** Optional close-up photo of the fabric (square crop preferred).
      Drop into /public/images/swatches/[slug].jpg. The glossary renders
      a dark gradient fallback when the file is missing. */
  swatchImage?: string
  /** Optional palette of colour variants — each entry is a swatch photo of
      the same fabric in a specific colourway. Rendered as a thumbnail grid
      in the expanded glossary panel when present. */
  colourSwatches?: Array<{ name: string; image: string }>
}

